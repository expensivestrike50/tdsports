"""Fetch each team's real form (last five matches before the game) for every match in the app.

Usage: python3 tools/fetch-form.py

For each match in api/v1/matches.json (build it first with tools/build-api.js) it finds the
ESPN event on that day's scoreboard for the competition, reads the "last five games" in
ESPN's match summary and writes form-data.js:

    TEAM_FORM[match id] = { home: [game, ...], away: [...] }   (most recent first)
    game = { date, opp, logo, f, a, res, comp, venue }          (f/a from the team's side)

Matches it can't find on ESPN are left out; the app then says form isn't available.
"""
import json
import os
import re
import time
import unicodedata
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UA = {'User-Agent': 'Mozilla/5.0 (TDsports prototype; team form)'}
CODES = {'UEFA Champions League': 'uefa.champions', 'UEFA Europa League': 'uefa.europa', 'Premier League': 'eng.1',
         'LaLiga': 'esp.1', 'Bundesliga': 'ger.1', 'Serie A': 'ita.1', 'Ligue 1': 'fra.1', 'MLS': 'usa.1',
         'Liga MX': 'mex.1', 'FIFA World Cup': 'fifa.world'}


def get(url):
    for attempt in range(4):
        try:
            data = json.loads(urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=30).read())
            time.sleep(0.2)
            return data
        except Exception:
            time.sleep(2 * (attempt + 1))
    return None


def norm(name):
    s = unicodedata.normalize('NFKD', name or '').encode('ascii', 'ignore').decode().lower()
    return set(w for w in re.split(r'[^a-z0-9]+', s) if len(w) > 2 and w not in {'fc', 'afc', 'cf', 'club', 'united', 'city'}) or {s}


def same(a, b):
    return bool(norm(a) & norm(b)) or (a or '').lower() == (b or '').lower()


def team_names(c):
    t = c.get('team') or {}
    return [t.get(k) for k in ('shortDisplayName', 'displayName', 'name', 'location', 'abbreviation') if t.get(k)]


def main():
    matches = json.load(open(os.path.join(ROOT, 'api', 'v1', 'matches.json'), encoding='utf-8'))['data']
    boards, form, missing = {}, {}, []
    for m in matches:
        code = CODES.get(m['competition'])
        if not code:
            missing.append(m['id'])
            continue
        # Kick-offs late in the evening in the Americas fall on the next UTC day: check both.
        events = []
        for day in {m['date'].replace('-', ''), time.strftime('%Y%m%d', time.gmtime(time.mktime(time.strptime(m['date'], '%Y-%m-%d')) + 86400))}:
            key = (code, day)
            if key not in boards:
                boards[key] = (get(f'https://site.api.espn.com/apis/site/v2/sports/soccer/{code}/scoreboard?dates={day}') or {}).get('events', [])
            events += boards[key]
        home, away = m['home']['name'], m['away']['name']
        ev = None
        for e in events:
            comps = (e.get('competitions') or [{}])[0].get('competitors') or []
            side = {c.get('homeAway'): c for c in comps}
            if 'home' in side and 'away' in side and any(same(home, n) for n in team_names(side['home'])) \
                    and any(same(away, n) for n in team_names(side['away'])):
                ev = e
                break
        if not ev:
            missing.append(m['id'])
            continue
        summary = get(f'https://site.api.espn.com/apis/site/v2/sports/soccer/{code}/summary?event={ev["id"]}') or {}
        comps = ev['competitions'][0]['competitors']
        side_of = {c['team']['id']: c['homeAway'] for c in comps}
        entry = {}
        for t in summary.get('lastFiveGames') or []:
            side = side_of.get(t['team']['id'])
            if not side:
                continue
            games = []
            for g in t.get('events') or []:
                at_home = g.get('atVs') != '@'
                hs, as_ = int(g.get('homeTeamScore') or 0), int(g.get('awayTeamScore') or 0)
                f, a = (hs, as_) if at_home else (as_, hs)
                res = (g.get('gameResult') or ('W' if f > a else 'D' if f == a else 'L')).lower()
                opp = g.get('opponent') or {}
                games.append({'date': (g.get('gameDate') or '')[:10], 'opp': opp.get('displayName') or '?',
                              'logo': g.get('opponentLogo') or opp.get('logo') or '', 'f': f, 'a': a, 'res': res,
                              'comp': g.get('leagueAbbreviation') or g.get('leagueName') or '', 'venue': 'H' if at_home else 'A'})
            entry[side] = sorted(games, key=lambda g: g['date'], reverse=True)
        if entry:
            form[m['id']] = entry
        else:
            missing.append(m['id'])
        print(f"{m['id']}: {ev.get('name')} {'ok' if entry else 'no form'}", flush=True)

    out = ['// Generated by tools/fetch-form.py from ESPN match summaries. Do not edit by hand.',
           '// Each team\'s last five matches before the game, most recent first.',
           f'const TEAM_FORM = {json.dumps(form, ensure_ascii=False)};', '']
    open(os.path.join(ROOT, 'form-data.js'), 'w', encoding='utf-8').write('\n'.join(out))
    print(f'{len(form)} matches with form; missing: {", ".join(missing) or "none"}')


if __name__ == '__main__':
    main()
